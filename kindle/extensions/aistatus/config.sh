# ⑤ 省电模式 / 怎么退出 ----------------------------------------------------
#    1 = 停掉原生的书架界面并让设备真正休眠（最省电）
#    0 = 保留原生界面（安全、随时能点「停止信息屏」），但耗电快得多，
#        而且原生界面会盖掉我们的画面，只能靠循环每次唤醒重贴
#
# 退出信息屏有四条路，且都必须是**故意**的动作：
#   1. 点屏幕两下（两下间隔不超过 EXIT_TAP_GAP 秒）—— 随手可用的出口
#      ⚠️ 数的是"人为唤醒"次数，**分不清你点在哪里**：框架停掉后拿不到坐标，
#         而内核的唤醒源清单里根本没有触摸屏（见 system_probe.txt）。
#         所以快速按两下电源键也算。图左上角那枚「点两下退出」只是提示，
#         不是热区 —— 点屏幕任何位置都算一下。
#      ⚠️ 所以"快速双击"是**没用**的：第一下把它叫醒，之后几秒它本来就醒着，
#         第二下不产生新的"唤醒"，只算一下。真正的动作是
#         「点一下 → 数两秒等它睡回去 → 再点一下」。
#      历史：上一版就是"两下"，当时正常使用中一碰就退，被撤掉（见提交 2357393）。
#      2026-09-26 用户明确要"双击退出"，接受误退风险换顺手；如果哪天发现它
#      自己退了，把下面的 EXIT_TAPS 调回 3 就行。
#   2. 点 documents 里的「停止信息屏」scriptlet
#      ⚠️ 但 STOP_FRAMEWORK=1 时书库是关着的，点不到它 —— 这正是第 1 条存在的理由。
#   3. USB 连电脑，在 extensions/aistatus/ 里新建一个空文件名叫 .stop
#      循环只在醒来时才检查这个文件，所以下面 STOP_CHECK_MAX_SLEEP 决定它最慢
#      多久生效。默认 600 = 最多 10 分钟。
#   4. 万能保底：长按电源键 40 秒强制重启，系统完全恢复原样
