CLOCK_SYNC_TOLERANCE=120    # 偏差超过多少秒才校（秒）

# ⑦b 时区 —— 决定屏幕上显示几点，和 ⑦ 是两件事
#
#    ⑦ 校的是 epoch（绝对时刻），这个管的是把 epoch 换算成「几点」时加多少。
#    Kindle 的时区通常是注册时从亚马逊账号拿的 —— 而 LanguageBreak 流程
#    本来就要求跳过注册、填假信息，所以这台机器拿不到时区，系统按 UTC 走。
#    后果：时钟是从设备系统时间画的，UTC 的机器会让屏幕上的时间**慢 8 小时**，
#    而且 ⑦ 的对表完全查不出来（epoch 是对的，只有换算错了）。
#
#    POSIX 的偏移符号是反的：东八区写 -8。中国没有夏令时，固定偏移全年正确。
#    换城市改这里；留空 = 不设置，跟随系统默认。
