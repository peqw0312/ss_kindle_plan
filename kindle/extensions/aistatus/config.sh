# ③ 本机时钟 ---------------------------------------------------------------
#    local = 图里时钟那块是留白的，由 Kindle 用**自己的系统时间**每分钟贴一张小图。
#            于是屏幕上每一分钟都是准的，而服务端一天只要出四次图。
#            需要 extensions/aistatus/clock/ 里有一整套精灵图（1440 张），
#            用 dashboard/tools/make_clock_assets.py 生成。
#    off   = 不贴时钟。**图里那块就是空白的**，看起来像少了一块，除非
#            你在 dashboard/config.yaml 里把 clock.mode 改回 image。
CLOCK_MODE=local

#    多久贴一次时钟（秒）。60 = 每分钟，时间永远是对的。
#    这是本项目唯一"费电"的地方：唤醒次数从每天几十次涨到 1440 次。
#    实测续航掉得厉害就把这个数调大（比如 300 = 每 5 分钟），代价是
#    屏幕上的时间会以 5 分钟为单位跳。
CLOCK_INTERVAL=60

#    贴图用的刷新波形。du 最快、不闪屏，适合这种小面积改动。
#    如果真机上 du 没反应（老固件可能不支持），改成 gl16 或 gc16 试试。
CLOCK_WAVE=du

# ④ 显示质量 ---------------------------------------------------------------
#    每 N 次整图刷新做一次全屏刷新，用来清残影。
#    每小时贴 60 次时钟会累积残影，所以整图这一下**每次都全刷**（=1），
#    等于每小时清一次鬼影。
FULL_REFRESH_EVERY=1

# ⑤ 省电模式 ---------------------------------------------------------------
# 1 = 停掉原生的书架界面并让设备真正休眠（最省电）
#     代价：KUAL 和书架界面在运行期间不可见
#     恢复：长按电源键 40 秒强制重启，系统会完全恢复原样
# 0 = 保留原生界面（安全、随时能用「停止信息屏」那个 scriptlet 停），但耗电快得多
STOP_FRAMEWORK=1

# 双击屏幕退出 ---------------------------------------------------------------
#    STOP_FRAMEWORK=1 会关掉书架界面，设备等于没有出口 —— 以前想恢复正常使用
#    只能长按电源 40 秒。这里补一个手势：
#    **连着碰两下屏幕（间隔不超过下面的秒数）就退出并回到桌面。**
#
#    实现上不需要读触摸屏：循环本来就分得清"这次唤醒是闹钟来的、还是有人碰的"
#    （见 aistatus.sh 的 secure_sleep），两次人为唤醒挨得近就算双击。
#
#    顺带一提：原生界面在恢复时会把我们的画面擦掉，所以"碰屏幕"这个动作本身就是
#    屏幕只剩一个时钟的元凶。现在它同时成了出口 —— 打不过就用它。
#    设 0 = 关掉这个手势（那时只剩长按电源这一条路）。嫌误触就调小到 4。
EXIT_TAP_GAP=8

# 1 = 刷完图让设备进入 suspend，靠 RTC 闹钟唤醒（配合 STOP_FRAMEWORK=1 使用）
USE_RTC_SLEEP=1

# 1 = 每次刷新前后关掉 WiFi 省电；0 = 一直保持 WiFi
WIFI_SLEEP=0

# ⑥ 网络 -------------------------------------------------------------------
