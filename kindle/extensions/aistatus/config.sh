# ② 整图刷新节奏 -----------------------------------------------------------
#    ★ 正常情况下这里**不用管**：云端每个响应都带一个 X-Next-Image 头，
#      告诉 Kindle 下一次几点换新图。设备照着它睡，一天只需要连四五次 WiFi，
#      而不是每小时去问一次（问 24 次里有 20 次拿回来的是完全相同的图）。
#      想改"几点换新图"，改的是 dashboard/config.yaml 的 cloud.refresh_at，
#      重新发布云端即可 —— 这边一个字节都不用动。
#
#    下面这几个值只在**云端没给头**的时候才生效，也就是：
#      · 走局域网备用地址（serve.py 是静态发文件的，不参与调度）
#      · 云端还是旧版本、没带这个头
#    留着的意义就是"问不到总得有个节奏"，不是主路径。
