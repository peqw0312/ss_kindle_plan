# ① 图片地址 ---------------------------------------------------------------
#    填**两个**：主地址失败会自动退到备用地址。留空表示不用。
#
#    ★ 主地址 = GitHub 仓库里那张由 Actions 定时生成的图。
#      **这台电脑不是服务器**，它不参与任何环节：改完代码 push 上去，
#      Actions 按点出图、提交回仓库，Kindle 直接找 GitHub 拿。
#      电脑关机、休眠、断网，都不影响这块屏。
#
#    备用地址留空是故意的：宁可让它失败并在日志里明写「所有地址都失败」，
#    也不要悄悄退到别处、拿回一张**不同版式**的图 —— 那会让人对着
#    "我改了怎么没生效"的屏幕白查半天（局域网当备胎时真发生过）。
#
#    注意 raw.githubusercontent.com 有约 5 分钟的 CDN 缓存。
#    一天只出四次图，这点延迟无所谓；但别指望 push 完立刻变。
#    两边都必须是 .png 结尾的**图片地址**，不是站点首页。
