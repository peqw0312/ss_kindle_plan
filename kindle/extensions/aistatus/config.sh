DASHBOARD_URL="https://raw.githubusercontent.com/peqw0312/ss_kindle_plan/main/docs/dashboard.png"
DASHBOARD_FALLBACK_URL=""

# ② 整图刷新节奏 -----------------------------------------------------------
#    ★ 走 GitHub 之后，**时刻表搬到了这里**（以前是云端每个响应塞一个
#      X-Next-Image 头告诉设备"几点再来"，GitHub 是静态文件，发不了自定义头）。
#      所以"几点换新图"现在由下面 REFRESH_AT 和 dashboard/config.yaml 的
#      cloud.refresh_at **两处各写一份**，改的时候要一起改 —— 不一致的后果是：
#      设备在没出图的点上去，拿回一张旧图，白连一次 WiFi。
#
#    一天就连四五次 WiFi，而不是每小时问一次（问 24 次有 20 次拿回的是同样的字节）。
REFRESH_AT="00:05 05:10 12:00 15:05"   # 北京时间，和 config.yaml 的 cloud.refresh_at 对齐

#    到点之后**再多等这么多秒**才去拉。Actions 从触发到把图提交回仓库要两三分钟，
#    raw.githubusercontent.com 还有一层约 5 分钟的 CDN 缓存 —— 卡在整点上必然拿到旧图。
REFRESH_LAG=600

#    下面几个只在"算不出下一个出图点"时兜底（REFRESH_AT 被清空或写坏了）。
UPDATE_INTERVAL=3600        # 兜底：白天多久去拉一次图（秒）
NIGHT_INTERVAL=10800        # 兜底：夜间多久去拉一次图（秒）
ACTIVE_START=6              # 活跃时段从几点开始（24 小时制）
ACTIVE_END=23               # 23 点以后转夜间节奏
#    注意：这些都只影响**整图**。时钟不受它们影响，见 ③。

# ③ 本机时钟 ---------------------------------------------------------------
#    local = 图里时钟那块是留白的，由 Kindle 用**自己的系统时间**每分钟贴一张小图。
#            于是屏幕上每一分钟都是准的，而服务端一天只要出四次图。
#            需要 extensions/aistatus/clock/ 里有一整套精灵图（1440 张），
#            用 dashboard/tools/make_clock_assets.py 生成。
#    off   = 彻底不要时间。**这是最省电的模式**：心跳不再每分钟一次，而是跟着
#            整图的节奏走 —— 一天醒 4~5 次，而不是 1440 次。
#            必须同时把电脑上 dashboard/config.yaml 的 clock.mode 也改成 off：
#              那边是 image → 图里会画一个最多六小时前的假时间（比没有更糟）
#              那边是 local  → 右上角永远是一块空白
#            改成 off 之后 clock/ 那 1440 张精灵图就用不上了，可以从 Kindle 删掉腾空间。
CLOCK_MODE=off

# --- 电量显示（右上角精灵图，样式 B：百分比大字 + 进度条）-------------------
#    电量只有设备自己知道，云端画不了 —— 所以整图里右上角是留白的，
#    由这里按当前电量贴一张 battery/NNN.png（000/010/…/100 共 11 档）。
#    精灵图用 dashboard/tools/make_battery_assets.py 生成，整目录拷进
#    extensions/aistatus/battery/。≤20% 的档位自带灰字「请充电」。
#    local = 每次刷完整图后补贴这一小块；off = 不贴，右上角留白（无害）。
BATTERY_MODE=local

#    贴图用的刷新波形。du 最快、不闪屏；老固件不支持就改 gl16 / gc16。
BATTERY_WAVE=du

#    多久贴一次时钟（秒）。只有 CLOCK_MODE=local 时才有意义。
#    60 = 每分钟，时间永远是对的；代价是唤醒次数从每天几十次涨到 1440 次。
#    嫌续航短又还想要时间，可以调大（比如 300 = 每 5 分钟），
#    屏幕上的分钟数会以 5 分钟为单位跳。
CLOCK_INTERVAL=60

#    贴图用的刷新波形。du 最快、不闪屏，适合这种小面积改动。
#    如果真机上 du 没反应（老固件可能不支持），改成 gl16 或 gc16 试试。
CLOCK_WAVE=du

# ④ 显示质量 ---------------------------------------------------------------
#    每 N 次整图刷新做一次全屏刷新，用来清残影。
#    CLOCK_MODE=local 时贴钟会累积残影，所以整图这一下默认每次都全刷（=1）。
#    CLOCK_MODE=off 时没有贴钟，想少闪屏可以把它调大（比如 4）。
FULL_REFRESH_EVERY=1

# ⑤ 省电模式 / 怎么退出 ----------------------------------------------------
#    1 = 停掉原生的书架界面并让设备真正休眠（最省电）
#    0 = 保留原生界面（安全、随时能点「停止信息屏」），但耗电快得多，
#        而且原生界面会盖掉我们的画面，只能靠循环每次唤醒重贴
#
# 退出信息屏有四条路，且都必须是**故意**的动作：
#   1. 快速连点屏幕三下（每两下间隔不超过 EXIT_TAP_GAP 秒）—— 随手可用的出口
#      ⚠️ 数的是"人为唤醒"次数，**分不清你点在哪里**：框架停掉后拿不到坐标，
#         而内核的唤醒源清单里根本没有触摸屏（见 system_probe.txt）。
#         所以快速按三下电源键也算。想做到"只有电量区域有效"得去读
#         /dev/input，是另一件事，先看触摸到底能不能叫醒这台机器。
#      上一版是"两下"，正常使用中一碰就退，已撤掉（见提交 2357393）。
#      三下 + 短间隔只能是故意的。
#   2. 点 documents 里的「停止信息屏」scriptlet
#      ⚠️ 但 STOP_FRAMEWORK=1 时书库是关着的，点不到它 —— 这正是第 1 条存在的理由。
#   3. USB 连电脑，在 extensions/aistatus/ 里新建一个空文件名叫 .stop
#      循环只在醒来时才检查这个文件，所以下面 STOP_CHECK_MAX_SLEEP 决定它最慢
#      多久生效。默认 600 = 最多 10 分钟。
#   4. 万能保底：长按电源键 40 秒强制重启，系统完全恢复原样
STOP_FRAMEWORK=1

#    要停掉的原生界面任务（upstart 的任务名，空格分隔）。
#    这台 PW3 上 /etc/init.d 是**空目录**，所以老写法 `/etc/init.d/framework stop`
#    一直返回 127（命令不存在）—— 界面其实从来没停过。任务名是跑 `initctl list`
#    从设备自己身上查出来的，不是照别的机型抄的：
#      framework   主框架
#      pillow      书架 / 桌面，也就是"主界面"本身
#      statusbar   顶部状态栏。**它是独立任务**，只停 framework 的话
#                  那个系统时钟照样在刷
#      webreader   浏览器
#    换机型时只改这一行，不用动脚本。
UI_JOBS="framework pillow statusbar webreader"

#    .stop 最慢多久被发现（秒）。关掉时钟之后心跳本来会拉长到几小时一次，
#    那 .stop 就等于没用了，所以这里封一个上限。
#    调小 → 退出更跟手，但醒得更勤；调大 → 更省电，但 .stop 生效慢。
#    600（10 分钟）= 一天醒 144 次，仍比贴钟时的 1440 次少一个数量级。
STOP_CHECK_MAX_SLEEP=600

#    连点几下算"故意要退出"，以及两下之间最多隔多少秒（超过就重新数）。
#    别把 EXIT_TAPS 调到 2 以下 —— 两下就是当年"正常使用中一碰就退"那个坑。
#    调大 EXIT_TAP_GAP 会让误退概率上升，调小则要求你点得更急。
EXIT_TAPS=3
EXIT_TAP_GAP=8

# 1 = 刷完图让设备进入 suspend，靠 RTC 闹钟唤醒（配合 STOP_FRAMEWORK=1 使用）
USE_RTC_SLEEP=1

# 1 = 每次刷新前后关掉 WiFi 省电；0 = 一直保持 WiFi
#
# ★ 保持 0。曾经以为"射频常开是 echo mem 睡不进去的原因"，把它改成 1 试过，
#   实测两组数据把这个结论推翻了：
#     WIFI_SLEEP=1 → 第一次睡 121s，随后 1s、1s 弹回（空转烧 CPU）
#     WIFI_SLEEP=0 → 181s / 178s / 175s，误差 1 秒内
#   真正让设备睡进去的是 wakealarm + 写 /sys/power/wakeup_count 那两处修复，
#   跟射频开不开没关系。而关射频反而带来一个新故障：**框架被停掉之后
#   WiFi 一旦掉线就再也连不上**（出现过连续 14 轮「WiFi 连接超时」，
#   屏幕只能靠 fallback.png 撑着）。
#   所以这里别再改回 1 —— 想省电去查唤醒源，不要拿射频开刀。
WIFI_SLEEP=0

# ⑥ 网络 -------------------------------------------------------------------
#    用来判断"网是不是真通了"。只是 ping 一下探个路，不下任何东西。
#
#    ★ 填外网地址还是网关，取决于**主地址在哪**：
#      主地址在云端（上面 ① 的第一行）→ 填**外网**地址，也就是现在这个；
#        填网关只能证明局域网通，证明不了能上外网，日志会给出错误的安慰。
#      只有局域网备用地址、不要云端 → 改成网关（192.168.x.1）。
#        那种情况下 Kindle 只需要够得着家里，断网也该能刷新。
#    填 IP 不填域名：省一次 DNS，也绕开某些固件的解析毛病。
#    ★ 跟着 ① 走：主地址在公网（GitHub）→ 必须探外网地址。
#      填成网关的话断网时它照样"ping 得通路由器"，于是日志误报 WiFi 已连通。
WIFI_TEST_IP="223.5.5.5"
WIFI_TIMEOUT=90             # 等 WiFi 连上的超时（秒）
HTTP_TIMEOUT=60             # 下载图片的超时（秒）

# ⑦ 设备时间校准 -----------------------------------------------------------
#    以前每个响应带一个 X-Epoch 头，Kindle 拿它对表。
#    ★ 走 GitHub 之后**这条路是死的** —— raw 是静态文件，发不了自定义头，
#      所以 sync_clock 找不到 X-Epoch 就静默返回（不报错、也不校）。
#      保留代码是因为它零副作用，哪天再跑一个自建服务就自动生效。
#
#    现在设备时间错了的后果变成这样：② 的时刻表是拿本机 `date +%H:%M` 算的，
#    钟不准 → 拉图的时点跟着错位（不是不刷，是刷得不是那个点），
#    而屏幕上那个"更新 HH:MM"是服务端写的，两者会对不上。
#    所以**先把时区（⑦b）设对**，那是最主要的一个错源。
#    真要校时：把 STOP_FRAMEWORK 临时改成 0 启动一次原生界面，让它自己对时。
CLOCK_SYNC=1
CLOCK_SYNC_TOLERANCE=120    # 偏差超过多少秒才校（秒）

# ⑦b 时区 —— 决定屏幕上显示几点，和 ⑦ 是两件事
#
#    ⑦ 校的是 epoch（绝对时刻），这个管的是把 epoch 换算成「几点」时加多少。
#    Kindle 的时区通常是注册时从亚马逊账号拿的 —— 而 LanguageBreak 流程
#    本来就要求跳过注册、填假信息，所以这台机器拿不到时区，系统按 UTC 走。
#    后果：时钟是从设备系统时间画的，UTC 的机器会让屏幕上的时间**慢 8 小时**，
#    而且 ⑦ 的对表完全查不出来（epoch 是对的，只有换算错了）。
#
#    POSIX 的偏移符号是反的：东八区写 -8。中国没有夏令时，固定偏移全年正确。
#    换城市改这里；留空 = 不设置，跟随系统默认。
TIMEZONE="CST-8"
[ -n "$TIMEZONE" ] && export TZ="$TIMEZONE"

