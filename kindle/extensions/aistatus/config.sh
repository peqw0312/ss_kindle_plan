# 1 = 刷完图让设备进入 suspend，靠 RTC 闹钟唤醒（配合 STOP_FRAMEWORK=1 使用）
#
# 现在填 **0** —— 但这条 2026-10-01 翻过一次车，别再当成"不睡就一定醒着"：
#   那天 22:11 那一班干完之后，23:10 那一班**日志一个字都没留**，一个多小时没醒。
#   原因是"我们不主动 `echo mem`"不等于"设备不挂起"—— 是 powerd 按自己的空闲
#   计时器把它 suspend 的；而一旦不走上面那条分支，就没人再往 wakealarm 里写闹钟，
#   于是挂起之后没有任何东西叫得醒它。**为了省电而关掉休眠，反而比开着更容易死睡。**
#   修法在 aistatus.sh 的 arm_wake()：不主动断电，但闹钟照样上，被挂起后靠它叫回来。
#
#   0 这一档换来的还是那些：心跳 = 整图节奏、.stop 一分钟内生效、电脑上按
#   「立刻出图」下一分钟上屏；也躲开了插着 USB 时 VBUS 让 `echo mem` 秒弹回。
